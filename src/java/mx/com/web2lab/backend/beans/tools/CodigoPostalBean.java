package mx.com.web2lab.backend.beans.tools;

public class CodigoPostalBean {

	private int kCodigo;
	
	private String scodigopostal;
	
	private String scolonia;
	
	private String sdelegacionmunicipio;
	
	private String sciudad;
	
	private String sestado;

	private int casentamiento;
	
	public int getKCodigo() {
		return kCodigo;
	}

	public void setKCodigo(int kCodigo) {
		this.kCodigo = kCodigo;
	}

	public String getScodigopostal() {
		return scodigopostal;
	}

	public void setScodigopostal(String scodigopostal) {
		this.scodigopostal = scodigopostal;
	}

	public String getScolonia() {
		return scolonia;
	}

	public void setScolonia(String scolonia) {
		this.scolonia = scolonia;
	}

	public String getSdelegacionmunicipio() {
		return sdelegacionmunicipio;
	}

	public void setSdelegacionmunicipio(String sdelegacionmunicipio) {
		this.sdelegacionmunicipio = sdelegacionmunicipio;
	}

	public String getSciudad() {
		return sciudad;
	}

	public void setSciudad(String sciudad) {
		this.sciudad = sciudad;
	}

	public String getSestado() {
		return sestado;
	}

	public void setSestado(String sestado) {
		this.sestado = sestado;
	}

	public int getCasentamiento() {
		return casentamiento;
	}

	public void setCasentamiento(int casentamiento) {
		this.casentamiento = casentamiento;
	}
}
