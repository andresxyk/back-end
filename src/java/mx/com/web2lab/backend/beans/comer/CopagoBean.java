package mx.com.web2lab.backend.beans.comer;

public class CopagoBean {
	private int cconvenio;
	private double pcopago;
	private double mcopago;
	private boolean bcopagopaciente;
	
	
	public int getCconvenio() {
		return cconvenio;
	}
	public void setCconvenio(int cconvenio) {
		this.cconvenio = cconvenio;
	}
	public double getPcopago() {
		return pcopago;
	}
	public void setPcopago(double pcopago) {
		this.pcopago = pcopago;
	}
	public double getMcopago() {
		return mcopago;
	}
	public void setMcopago(double mcopago) {
		this.mcopago = mcopago;
	}
	public boolean isBcopagopaciente() {
		return bcopagopaciente;
	}
	public void setBcopagopaciente(boolean bcopagopaciente) {
		this.bcopagopaciente = bcopagopaciente;
	}
	
	
}
